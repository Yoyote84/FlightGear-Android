#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MANIFEST="$ROOT/native/dependencies.lock"
SOURCE_ROOT="${SOURCE_ROOT:-$ROOT/native/src}"
STAMP="${SOURCE_STAMP:-$ROOT/native/build/source-stamp.txt}"

fail() { echo "FAIL: $*" >&2; exit 1; }

[[ -f "$MANIFEST" ]] || fail "missing native/dependencies.lock"
command -v git >/dev/null 2>&1 || fail "git is required"

mkdir -p "$SOURCE_ROOT" "$(dirname "$STAMP")"

python3 - "$MANIFEST" "$SOURCE_ROOT" "$STAMP" <<'PY'
import subprocess
import sys
from pathlib import Path

manifest = Path(sys.argv[1]).read_text(encoding="utf-8")
source_root = Path(sys.argv[2])
stamp_path = Path(sys.argv[3])

sections = {}
current = None
for raw in manifest.splitlines():
    line = raw.strip()
    if not line or line.startswith("#"):
        continue
    if line.startswith("[") and line.endswith("]"):
        current = line[1:-1]
        sections[current] = {}
    elif current and "=" in line:
        key, value = [part.strip() for part in line.split("=", 1)]
        sections[current][key] = value

required = ("flightgear", "simgear", "openscenegraph")
for name in required:
    if name not in sections:
        raise SystemExit(f"missing [{name}] in dependency manifest")

stamp_lines = ["# Generated by native/bootstrap/fetch_sources.sh"]
for name in required:
    cfg = sections[name]
    repository = cfg["repository"]
    revision = cfg["revision"]
    target = source_root / name
    if target.exists() and not (target / ".git").exists():
        raise SystemExit(f"source destination exists but is not a Git checkout: {target}")
    if not target.exists():
        subprocess.run(["git", "clone", "--no-checkout", repository, str(target)], check=True)
    subprocess.run(["git", "-C", str(target), "fetch", "--depth", "1", "origin", revision], check=True)
    subprocess.run(["git", "-C", str(target), "checkout", "--detach", revision], check=True)
    actual = subprocess.check_output(["git", "-C", str(target), "rev-parse", "HEAD"], text=True).strip()
    if actual != revision:
        raise SystemExit(f"revision mismatch for {name}: expected {revision}, got {actual}")
    stamp_lines.append(f"{name}={actual}")

stamp_path.write_text("\n".join(stamp_lines) + "\n", encoding="utf-8")
print(f"PASS: pinned sources fetched under {source_root}")
PY
